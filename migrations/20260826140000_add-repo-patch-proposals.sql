-- repo_patch: the harness's only route into a repository.
--
-- An operator agent reads a product's working tree and drafts a change. It
-- cannot commit that change and holds no credential that could: the archive it
-- read arrived through a signed URL and its container has no GitHub identity.
-- What it produces is a proposal, and a proposal becomes a commit only when a
-- person approves it — at which point github-sync writes it under that
-- person's own authority, re-derived from their JWT exactly as every other
-- lifecycle write already is.
--
-- This is D2 extended to git. The whole harness runtime is arranged so that
-- this migration is the only place where agent work reaches an external system,
-- and that it does so behind the approval gate the platform already had.

-- ---------------------------------------------------------------------------
-- The new action
-- ---------------------------------------------------------------------------

-- CHECK constraints enumerate the actions, so both have to learn the new one.
-- Widening a CHECK means dropping and recreating it.
--
-- The old constraints were written inline, so their names were generated by
-- PostgreSQL. Dropping by a guessed name would silently do nothing when the
-- guess is wrong, and the new constraint would then sit alongside an old one
-- that still rejects 'repo_patch' — a failure that would only surface the first
-- time someone tried to approve a patch. So they are looked up instead.
DO $$
DECLARE
  target RECORD;
BEGIN
  FOR target IN
    SELECT rel.relname AS table_name, con.conname AS constraint_name
    FROM pg_constraint con
    JOIN pg_class rel ON rel.oid = con.conrelid
    JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
    WHERE nsp.nspname = 'public'
      AND rel.relname IN ('agents', 'agent_proposals')
      AND con.contype = 'c'
      AND pg_get_constraintdef(con.oid) LIKE '%lifecycle_advance%'
  LOOP
    EXECUTE format(
      'ALTER TABLE public.%I DROP CONSTRAINT %I',
      target.table_name,
      target.constraint_name
    );
  END LOOP;
END;
$$;

ALTER TABLE public.agents
  ADD CONSTRAINT agents_allowed_actions_check
  CHECK (allowed_actions <@ ARRAY[
    'knowledge_note', 'task_create', 'task_update',
    'status_update', 'lifecycle_advance', 'repo_patch'
  ]::TEXT[]);

ALTER TABLE public.agent_proposals
  ADD CONSTRAINT agent_proposals_action_check
  CHECK (action IN (
    'knowledge_note', 'task_create', 'task_update',
    'status_update', 'lifecycle_advance', 'repo_patch'
  ));

-- Where an approved patch ends up. Null until github-sync reports a commit, so
-- "approved but not yet committed" is a state the UI can see and offer to
-- retry, rather than a silent divergence between the platform and the repo.
ALTER TABLE public.agent_proposals
  ADD COLUMN commit_sha TEXT
    CHECK (commit_sha IS NULL OR commit_sha ~ '^[0-9a-f]{7,40}$'),
  ADD COLUMN commit_error TEXT
    CHECK (commit_error IS NULL OR char_length(commit_error) <= 500);

-- github_sync_log enumerates its actions too. Without this the audit insert
-- would violate the CHECK, and because logSync deliberately swallows its own
-- errors — an audit failure must never fail a push that worked — the result
-- would be a commit path that silently records nothing.
ALTER TABLE public.github_sync_log
  DROP CONSTRAINT IF EXISTS github_sync_log_action_check;

ALTER TABLE public.github_sync_log
  ADD CONSTRAINT github_sync_log_action_check
  CHECK (action IN (
    'save_credentials', 'link', 'unlink',
    'push_artifact', 'delete_artifact', 'push_manifest',
    'apply_agent_patch'
  ));

-- ---------------------------------------------------------------------------
-- Approval
-- ---------------------------------------------------------------------------
-- The only branch in decide_agent_proposal that performs no write of its own.
--
-- It cannot: committing needs the GitHub API, and PostgreSQL is not going to
-- make that call. What this branch does is take the decision under the same
-- lock as every other action — which is what stops two people approving the
-- same patch and committing it twice — and leave the write to the application,
-- which then reports the commit back through record_agent_proposal_commit.
--
-- Every other line of the function is carried forward verbatim.

CREATE OR REPLACE FUNCTION public.decide_agent_proposal(
  p_proposal_id UUID,
  p_decision TEXT,
  p_decision_note TEXT DEFAULT NULL,
  p_waiver_reason TEXT DEFAULT NULL
)
RETURNS public.agent_proposals
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  actor UUID := (SELECT auth.uid());
  prop public.agent_proposals;
  ag public.agents;
  payload JSONB;
  new_id UUID;
  new_type TEXT;
  target_task public.product_tasks;
  waiver TEXT := nullif(btrim(coalesce(p_waiver_reason, '')), '');
  result public.agent_proposals;
  file_count INTEGER;
BEGIN
  IF p_decision NOT IN ('approve', 'reject') THEN
    RAISE EXCEPTION 'decision must be approve or reject';
  END IF;

  IF NOT public.is_active_member() THEN
    RAISE EXCEPTION 'only active members can decide proposals';
  END IF;

  SELECT * INTO prop FROM public.agent_proposals
  WHERE id = p_proposal_id FOR UPDATE;

  IF prop.id IS NULL THEN
    RAISE EXCEPTION 'proposal not found';
  END IF;

  IF prop.status <> 'pending' THEN
    RAISE EXCEPTION 'proposal has already been %', prop.status;
  END IF;

  IF p_decision = 'reject' THEN
    UPDATE public.agent_proposals
    SET status = 'rejected',
        decided_by = actor,
        decided_at = now(),
        decision_note = nullif(btrim(coalesce(p_decision_note, '')), '')
    WHERE id = prop.id
    RETURNING * INTO result;
    RETURN result;
  END IF;

  SELECT * INTO ag FROM public.agents WHERE user_id = prop.agent_id;

  IF ag.user_id IS NULL THEN
    RAISE EXCEPTION 'proposing agent no longer exists';
  END IF;

  IF NOT ag.enabled THEN
    RAISE EXCEPTION 'agent % is disabled', ag.handle;
  END IF;

  IF NOT (prop.action = ANY (ag.allowed_actions)) THEN
    RAISE EXCEPTION 'agent % is not permitted to propose %', ag.handle, prop.action;
  END IF;

  payload := prop.payload;

  IF prop.action = 'knowledge_note' THEN
    INSERT INTO public.knowledge_items (kind, title, content, status, author_id)
    VALUES ('note', payload ->> 'title', payload ->> 'content', 'draft', actor)
    RETURNING id INTO new_id;
    new_type := 'knowledge_item';

    IF prop.product_id IS NOT NULL THEN
      INSERT INTO public.knowledge_item_products (knowledge_item_id, product_id)
      VALUES (new_id, prop.product_id)
      ON CONFLICT DO NOTHING;
    END IF;

  ELSIF prop.action = 'task_create' THEN
    INSERT INTO public.product_tasks (product_id, title, notes, due_date, assignee_id, created_by)
    VALUES (
      prop.product_id,
      payload ->> 'title',
      payload ->> 'notes',
      nullif(payload ->> 'due_date', '')::DATE,
      nullif(payload ->> 'assignee_id', '')::UUID,
      actor
    )
    RETURNING id INTO new_id;
    new_type := 'product_task';

  ELSIF prop.action = 'task_update' THEN
    SELECT * INTO target_task FROM public.product_tasks
    WHERE id = (payload ->> 'task_id')::UUID;

    IF target_task.id IS NULL THEN
      RAISE EXCEPTION 'task not found';
    END IF;

    UPDATE public.product_tasks
    SET title = coalesce(payload ->> 'title', title),
        status = coalesce(payload ->> 'status', status),
        due_date = coalesce(nullif(payload ->> 'due_date', '')::DATE, due_date)
    WHERE id = target_task.id;

    new_id := target_task.id;
    new_type := 'product_task';

  ELSIF prop.action = 'status_update' THEN
    INSERT INTO public.status_updates (
      product_id, author_id, source_type, source_ref,
      health, stage, summary, details
    )
    VALUES (
      prop.product_id,
      actor,
      'manual',
      jsonb_build_object(
        'via', 'agent',
        'agent', ag.handle,
        'proposal_id', prop.id,
        'message_id', prop.message_id,
        'run_id', prop.run_id
      ),
      payload ->> 'health',
      payload ->> 'stage',
      payload ->> 'summary',
      payload ->> 'details'
    )
    RETURNING id INTO new_id;
    new_type := 'status_update';

  ELSIF prop.action = 'lifecycle_advance' THEN
    PERFORM public.advance_lifecycle_phase(
      (payload ->> 'phase_id')::UUID,
      payload ->> 'state',
      waiver
    );
    new_id := (payload ->> 'phase_id')::UUID;
    new_type := 'lifecycle_phase';

  ELSIF prop.action = 'repo_patch' THEN
    -- Validated here and written nowhere. The commit is made by github-sync
    -- from the application, under the approver's own JWT, because that
    -- function is the only holder of the org PAT and the only place the
    -- owner-or-admin rule for a product's repository is enforced.
    --
    -- What this branch guarantees is that no second approval can race the
    -- first: the row is locked, and the caller only reaches the commit after
    -- this transaction has moved the proposal out of 'pending'.
    IF prop.product_id IS NULL THEN
      RAISE EXCEPTION 'a repository patch must belong to a product';
    END IF;

    IF jsonb_typeof(payload -> 'files') <> 'array' THEN
      RAISE EXCEPTION 'a repository patch must carry a files array';
    END IF;

    file_count := jsonb_array_length(payload -> 'files');

    IF file_count = 0 THEN
      RAISE EXCEPTION 'a repository patch must change at least one file';
    END IF;

    -- A bound rather than a judgement about what is reasonable. An agent that
    -- has decided to rewrite two hundred files has misunderstood the task, and
    -- a human approving that from a card cannot have read it.
    IF file_count > 20 THEN
      RAISE EXCEPTION 'a repository patch may not change more than 20 files at once';
    END IF;

    IF nullif(btrim(coalesce(payload ->> 'message', '')), '') IS NULL THEN
      RAISE EXCEPTION 'a repository patch must carry a commit message';
    END IF;

    new_id := prop.product_id;
    new_type := 'repo_patch';

  ELSE
    RAISE EXCEPTION 'unknown proposal action %', prop.action;
  END IF;

  UPDATE public.agent_proposals
  SET status = 'approved',
      decided_by = actor,
      decided_at = now(),
      decision_note = nullif(btrim(coalesce(p_decision_note, '')), ''),
      result_type = new_type,
      result_id = new_id
  WHERE id = prop.id
  RETURNING * INTO result;

  UPDATE public.messages
  SET promoted_to_type = new_type,
      promoted_to_id = new_id
  WHERE id = prop.message_id;

  UPDATE public.agent_proposals
  SET status = 'superseded', decided_at = now()
  WHERE run_id IS NOT NULL
    AND run_id = prop.run_id
    AND id <> prop.id
    AND status = 'pending';

  INSERT INTO public.notifications (
    user_id, type, message_id, channel_id, actor_id, title, body
  )
  SELECT DISTINCT m.author_id, 'proposal_decided', prop.message_id, prop.channel_id,
         actor,
         '@' || ag.handle || ' proposal approved',
         left(prop.reasoning, 2000)
  FROM public.messages m
  WHERE m.id = (
    SELECT parent_id FROM public.messages WHERE id = prop.message_id
  )
  AND m.author_id IS NOT NULL
  AND m.author_id <> actor;

  RETURN result;
END;
$$;

GRANT EXECUTE ON FUNCTION public.decide_agent_proposal(UUID, TEXT, TEXT, TEXT)
TO authenticated;

-- ---------------------------------------------------------------------------
-- Recording the commit
-- ---------------------------------------------------------------------------
-- Called after github-sync has committed, by the same approver. Deliberately
-- narrow: it can only annotate a proposal that this caller already approved,
-- and only one that is waiting on a commit. It cannot approve anything, and it
-- cannot touch a proposal decided by somebody else.

CREATE OR REPLACE FUNCTION public.record_agent_proposal_commit(
  p_proposal_id UUID,
  p_commit_sha TEXT DEFAULT NULL,
  p_error TEXT DEFAULT NULL
)
RETURNS public.agent_proposals
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  actor UUID := (SELECT auth.uid());
  result public.agent_proposals;
BEGIN
  IF NOT public.is_active_member() THEN
    RAISE EXCEPTION 'only active members can record a commit';
  END IF;

  UPDATE public.agent_proposals
  SET commit_sha = nullif(btrim(coalesce(p_commit_sha, '')), ''),
      commit_error = left(nullif(btrim(coalesce(p_error, '')), ''), 500)
  WHERE id = p_proposal_id
    AND action = 'repo_patch'
    AND status = 'approved'
    AND decided_by = actor
    AND commit_sha IS NULL
  RETURNING * INTO result;

  IF result.id IS NULL THEN
    RAISE EXCEPTION 'no patch of yours is waiting to be committed';
  END IF;

  RETURN result;
END;
$$;

REVOKE ALL ON FUNCTION public.record_agent_proposal_commit(UUID, TEXT, TEXT)
FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_agent_proposal_commit(UUID, TEXT, TEXT)
TO authenticated;

